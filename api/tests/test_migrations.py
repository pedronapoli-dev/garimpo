from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Connection, inspect, select
from sqlalchemy.pool import StaticPool

from app.db import create_db_engine
from app.models import User

PYPROJECT = Path(__file__).parent.parent / "pyproject.toml"


@pytest.fixture
def connection() -> Iterator[Connection]:
    engine = create_db_engine("sqlite://", poolclass=StaticPool)
    with engine.connect() as connection:
        yield connection
    engine.dispose()


def alembic_config(connection: Connection) -> Config:
    config = Config(toml_file=PYPROJECT)
    config.attributes["connection"] = connection
    return config


def test_upgrade_head_creates_tables_and_dev_curator(connection: Connection) -> None:
    command.upgrade(alembic_config(connection), "head")

    tables = set(inspect(connection).get_table_names())
    assert {"users", "recommendations", "tags", "recommendation_tags"} <= tables
    emails = connection.scalars(select(User.email)).all()
    assert emails == ["curator@garimpo.local"]


def test_models_match_migrations_reports_no_drift(connection: Connection) -> None:
    config = alembic_config(connection)
    command.upgrade(config, "head")

    # Raises AutogenerateDiffsDetected when models.py and the migrations diverge.
    command.check(config)


def test_downgrade_base_removes_tables(connection: Connection) -> None:
    config = alembic_config(connection)
    command.upgrade(config, "head")
    command.downgrade(config, "base")

    assert inspect(connection).get_table_names() == ["alembic_version"]
